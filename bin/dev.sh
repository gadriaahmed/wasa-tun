#!/usr/bin/env bash
###############################################################################
# Single entrypoint: build Wasabi and start the local Docker Compose stack.
###############################################################################
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "${ROOT}"

# Wasabi requires JDK 17+ to build and run; bytecode targets Java 8 for Jersey 1.x compatibility.
ensure_java() {
  if [ -n "${JAVA_HOME:-}" ] && [ -x "${JAVA_HOME}/bin/java" ]; then
    java_major="$("${JAVA_HOME}/bin/java" -version 2>&1 | sed -n 's/.* version "\([0-9]*\).*/\1/p' | head -1)"
    if [ -n "${java_major}" ] && [ "${java_major}" -ge 17 ] 2>/dev/null; then
      export PATH="${JAVA_HOME}/bin:${PATH}"
      return 0
    fi
  fi
  for jdk in 17 21 25; do
    if jdk_home="$(/usr/libexec/java_home -v "${jdk}" 2>/dev/null)"; then
      export JAVA_HOME="${jdk_home}"
      export PATH="${JAVA_HOME}/bin:${PATH}"
      return 0
    fi
  done
  echo "error: JDK 17+ is required to build Wasabi." >&2
  echo "Install Temurin 17, e.g.: brew install --cask temurin@17" >&2
  echo "  export JAVA_HOME=\$(/usr/libexec/java_home -v 17)" >&2
  exit 1
}
ensure_java

profile="${WASABI_PROFILE:-development}"
do_build=true
start_react=true
compose_args=(--build)

usage() {
  cat <<EOF
usage: $(basename "$0") [options]

options:
  --no-build          Skip Maven/UI assembly (reuse existing modules/main/target/*)
  --no-ui             Skip starting the React dev server on :3000
  --profile PROFILE   Maven profile (default: development)
  --build             Force docker compose build (passes --build)
  -h, --help          Show this help

Examples:
  ./bin/dev.sh
  ./bin/dev.sh --no-build
  make dev
EOF
}

while [ $# -gt 0 ]; do
  case "$1" in
    --no-build) do_build=false ;;
    --no-ui) start_react=false ;;
    --profile) shift; profile="${1:?--profile requires a value}" ;;
    --build) compose_args+=(--build) ;;
    -h|--help) usage; exit 0 ;;
    *) echo "error: unknown option: $1" >&2; usage; exit 1 ;;
  esac
  shift
done

if [ "${do_build}" = true ]; then
  echo "==> Building Wasabi (profile=${profile})..."
  ./bin/build.sh -b true -p "${profile}"
fi

echo "==> Resolving WASABI_APP_ID from Maven..."
WASABI_APP_ID="$("${ROOT}/bin/mvn.sh" -f modules/main/pom.xml -P"${profile}" help:evaluate \
  -Dexpression=application.name -q -DforceStdout -B \
  -Dorg.slf4j.simpleLogger.log.org.apache.maven.cli.transfer.Slf4jMavenTransferListener=error)"

app_dir="modules/main/target/${WASABI_APP_ID}"
if [ ! -d "${app_dir}" ]; then
  echo "error: expected build output at ${app_dir}" >&2
  echo "Run without --no-build or check the profile." >&2
  exit 1
fi

cat > .env <<EOF
# Generated by bin/dev.sh — do not commit (.env is gitignored)
WASABI_APP_ID=${WASABI_APP_ID}
EOF

echo "==> Starting Docker Compose (WASABI_APP_ID=${WASABI_APP_ID})..."
./bin/compose.sh up -d "${compose_args[@]}"

echo "==> Waiting for API..."
for i in $(seq 1 90); do
  if curl -sf http://localhost:8088/api/v1/ping >/dev/null 2>&1; then
    break
  fi
  if [ "${i}" -eq 90 ]; then
    echo "warning: API not ready after 180s — check: ./bin/compose.sh logs -f wasabi" >&2
  fi
  sleep 2
done

if [ "${start_react}" = true ]; then
  ./bin/ui-react-dev.sh start
  sleep 2
  if ! curl -sf http://localhost:3000/ >/dev/null 2>&1; then
    echo "warning: React UI is not responding on :3000 — run: ./bin/ui-react-dev.sh restart" >&2
    echo "  log: ${ROOT}/.ui-react.log" >&2
  fi
fi

echo ""
echo "Stack running:"
echo "  API ping:   http://localhost:8088/api/v1/ping"
echo "  Legacy UI:  http://localhost:8088/  (login: admin/admin)"
if [ "${start_react}" = true ]; then
  echo "  React UI:   http://localhost:3000  (proxies /api/v1 to :8088)"
fi
echo ""
echo "Stop:  make stop   (backend + React dev server)"
echo "Logs:  ./bin/compose.sh logs -f wasabi"
